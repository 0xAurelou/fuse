#!/usr/bin/env python3
"""Generate real-transition Solidity vectors from the independent integer ledger.

Custody in the new adapter settles each outcome atomically, so reference resolve
and settle_cash are one observed action. Retains all prior experimental models.
"""
from pathlib import Path

from release_accounting import DAY, Ledger, Limits

ROOT = Path(__file__).resolve().parent.parent
START = 1_793_318_400_000
INITIAL_CUSTOMER = 10_000_000 * 1_000_000


def vectors():
    ledger = Ledger(START, Limits(1_000_000_000_000,
                    {a: 2_000_000_000_000 for a in ('BTC', 'ETH', 'HYPE')},
                    3_000_000_000_000, 0, 0, 0))
    actions, snapshots = [], []
    customer = INITIAL_CUSTOMER

    def record(kind, key=0, amount=0, asset=0, multiplier=0, canonical=0):
        actions.append((kind, ledger.clock//1000, canonical//1000, key, amount, asset, multiplier))
        row = [ledger.cash, ledger.open_exposure, ledger.operator_due, ledger.backing_due,
               ledger.fees, ledger.backing, ledger.realized, ledger.day, customer]
        for key in range(1, 4):
            lot = ledger.lots.get(key, ledger.archived.get(key))
            row += [lot.equity, ledger.lot_exposure(key), lot.pnl, lot.mark,
                    ledger.max_withdrawal(key) if key in ledger.lots else 0] if lot else [0]*5
        snapshots.append(row)

    def deposit(owner, amount):
        ledger.paused = True
        key = ledger.deposit(owner, amount, ledger.clock)
        record(0, key, amount)
        ledger.paused = False
        return key

    def accept(asset, stake, multiplier):
        nonlocal customer
        key = len(ledger.bets)+1
        ledger.accept(str(key), ('BTC', 'ETH', 'HYPE')[asset], stake, multiplier, ledger.clock+1000)
        customer -= stake
        record(1, key, stake, asset, multiplier)
        return key

    def resolve(key, outcome, observed=None, kind=None):
        nonlocal customer
        bet = ledger.bets[str(key)]
        canonical = bet.start+1000 if outcome == 3 else bet.expiry
        observed = max(ledger.clock+1000, bet.expiry) if observed is None else observed
        ledger.resolve(str(key), {2:'win', 3:'loss', 4:'void'}[outcome], canonical, observed_at=observed)
        if outcome in (2, 3):
            ledger.settle_cash(str(key), observed)
        customer += bet.payout if outcome == 2 else bet.stake if outcome == 4 else 0
        record(outcome if kind is None else kind, key, canonical=canonical)

    def withdraw(key, amount):
        ledger.withdraw(key, amount, ledger.clock+1000)
        record(5, key, amount)

    def close(need=0):
        ledger.close(ledger.cutoff, ledger.cutoff, 0, 0, need)
        record(6, ledger.day-1, need)

    def pay(day):
        ledger.pay_close(day, ledger.clock+1000)
        record(7, day)

    deposit('alice', 2000)
    deposit('bob', 2000)
    one = accept(0, 1000, 2)
    withdraw(1, 1500)
    resolve(one, 2)
    close()
    deposit('newcomer', 2000)
    for asset, multiplier, stake in ((1, 5, 101), (2, 10, 59)):
        key = accept(asset, stake, multiplier)
        resolve(key, 3)
    close(100)
    pay(1)
    # Carry losses through recovery, interleave unresolved bets and free exits.
    one = accept(0, 197, 2)
    two = accept(2, 17, 25)
    withdraw(2, min(100, ledger.max_withdrawal(2)))
    resolve(two, 4)
    resolve(one, 2)
    close()
    # Exercise asymmetric integer splits across additional market/payout pairs.
    # The complete advertised menu has separate onchain coverage.
    for asset, multiplier in ((0, 50), (1, 100), (2, 250)):
        key = accept(asset, 1, multiplier)
        resolve(key, 3)
    close()
    # Authenticated prior-day loss observed after cutoff, after free principal exits.
    key = accept(0, 10, 2)
    late = ledger.cutoff+10_000
    released = min(100, ledger.max_withdrawal(2))
    ledger.withdraw(2, released, late)
    record(5, 2, released)
    resolve(key, 3, observed=late+1000)
    close(20)
    pay(4)
    # A final void determined two boundaries later retains risk through both.
    key = accept(1, 20, 2)
    canonical = ledger.cutoff+DAY+10_000
    ledger.queue_final_void(str(key), canonical)
    record(8, key, canonical=canonical)
    close()
    close()
    ledger.resolve(str(key), 'void', canonical, observed_at=ledger.clock)
    customer += ledger.bets[str(key)].stake
    record(9, key, canonical=canonical)
    close()
    ledger.check()
    return actions, snapshots


def render():
    actions, snapshots = vectors()
    lines = ['// SPDX-License-Identifier: MIT', 'pragma solidity ^0.8.24;', '',
             '// Generated by scripts/generate_daily_accounting_vectors.py; do not edit.',
             'library DailyAccountingVectors {',
             f'    uint256 internal constant START = {START//1000};',
             f'    uint256 internal constant COUNT = {len(actions)};',
             '    struct Action { uint8 kind; uint64 at; uint64 canonical; uint256 key; uint256 amount; uint8 asset; uint256 multiplier; }',
             '    function action(uint256 i) internal pure returns (Action memory) {']
    for i, row in enumerate(actions):
        lines.append(f'        if (i == {i}) return Action('+', '.join(map(str, row))+');')
    lines += ['        revert();', '    }',
              '    function expected(uint256 i) internal pure returns (int256[24] memory) {']
    for i, row in enumerate(snapshots):
        lines.append(f'        if (i == {i}) return [int256({row[0]}), '+', '.join(map(str, row[1:]))+'];')
    lines += ['        revert();', '    }', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    path = ROOT/'test/fixtures/DailyAccountingVectors.sol'
    path.write_text(render())
    print(path)
