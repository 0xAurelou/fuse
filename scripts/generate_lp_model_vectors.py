#!/usr/bin/env python3
"""Generate Solidity expectations from the independent integer LP projection."""
from pathlib import Path
from contract_lp_model import LPModel, USDC, DAY, scheduled_budget

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ('cash', 'assets', 'fee', 'reserved', 'reserve', 'supply', 'pnl',
          'hwm_assets', 'hwm_shares', 'published', 'claimed', 'capital_seconds', 'index')


def trajectory():
    m = LPModel(1_700_000_000)
    m.deposit('protocol', 1_000_000 * USDC)
    m.finalize(0, 100 * USDC, 0)
    m.set_phase(1)
    m.whitelist.update(('alice', 'bob'))
    m.publish_capacity(1_000_000 * USDC, m.now + 3600)
    m.finalize(0, 100 * USDC, 0)
    rows = [m.snapshot()]
    m.deposit('alice', 123_456_789)
    rows.append(m.snapshot())
    m.finalize(2000 * USDC, 100 * USDC, 0)
    rows.append(m.snapshot())
    m.finalize(-1000 * USDC, 100 * USDC, 0)
    rows.append(m.snapshot())
    request = m.request_exit('alice', m.shares['alice'] // 2)
    m.deposit('bob', 321 * USDC)
    rows.append(m.snapshot())
    m.clock(m.start + DAY)
    m.checkpoint()
    m.liability_seconds[1] = m.capital_seconds[1] // 7
    m.resume()
    m.publish(1)
    rows.append(m.snapshot())
    m.clock(m.start + 2 * DAY)
    m.finalize(0, 100 * USDC, 0)
    m.resume()
    m.fund_reserve(m.fee)
    m.finalize(0, 100 * USDC, 0)
    m.fulfill(request)
    rows.append(m.snapshot())
    m.claim_exit(request, shares=m.exits[request-1].shares // 3)
    rows.append(m.snapshot())
    m.claim_exit(request, assets=m.exits[request-1].assets - m.exits[request-1].claimed_assets)
    rows.append(m.snapshot())
    m.clock(m.start + 31 * DAY)
    m.claim_reward(1, 'alice')
    m.claim_reward(1, 'bob')
    rows.append(m.snapshot())
    return rows


def render():
    lines = ['// SPDX-License-Identifier: MIT', 'pragma solidity ^0.8.24;',
             '// Generated by scripts/generate_lp_model_vectors.py; do not hand edit.',
             'library LPModelVectors {',
             '    function row(uint256 i) internal pure returns (uint256[13] memory) {']
    for i, row in enumerate(trajectory()):
        values = ', '.join('uint256(' + str(row[f]) + ')' for f in FIELDS)
        lines.append(f'        if (i == {i}) return [{values}];')
    lines += ['        revert("unknown vector");', '    }',
              '    function budget(uint256 i) internal pure returns (uint256) {']
    for i in range(1, 91):
        lines.append(f'        if (i == {i}) return {scheduled_budget(i)};')
    lines += ['        return 0;', '    }', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    target = ROOT / 'test/fixtures/LPModelVectors.sol'
    target.parent.mkdir(exist_ok=True)
    target.write_text(render())
    print(target)
